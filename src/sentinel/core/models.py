from datetime import datetime, timezone
from typing import Dict, List, Any, Optional
from pydantic import BaseModel, Field


class SecurityEvent(BaseModel):
    """Normalized security log event (Sysmon, CloudTrail, Auditd, etc.)."""
    event_id: str = Field(..., description="Unique event identifier or hash")
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    event_source: str = Field(..., description="Source system e.g. 'sysmon', 'aws_cloudtrail', 'auditd'")
    data: Dict[str, Any] = Field(default_factory=dict, description="Arbitrary event fields")


class DetectionRule(BaseModel):
    """Detection-as-Code (DaC) Rule Definition."""
    id: str = Field(..., description="Unique rule UUID or slug")
    title: str = Field(..., description="Human-readable threat title")
    description: str = Field(..., description="Threat context and behavior summary")
    severity: str = Field(default="MEDIUM", description="LOW, MEDIUM, HIGH, CRITICAL")
    mitre_tactics: List[str] = Field(default_factory=list, description="MITRE ATT&CK Tactics (e.g. Execution)")
    mitre_techniques: List[str] = Field(default_factory=list, description="MITRE ATT&CK Techniques (e.g. T1059.001)")
    logsource: Dict[str, str] = Field(..., description="Log source requirements e.g. {'category': 'process_creation'}")
    selection: Dict[str, Any] = Field(..., description="Field-value matching rules")
    containment_playbook: List[str] = Field(default_factory=list, description="Prescribed SOC containment steps")


class Alert(BaseModel):
    """Enriched security alert generated by the detection engine."""
    alert_id: str
    rule_id: str
    rule_title: str
    severity: str
    mitre_techniques: List[str]
    timestamp: str
    matched_event: SecurityEvent
    extracted_iocs: Dict[str, List[str]] = Field(default_factory=dict)
    containment_playbook: List[str] = Field(default_factory=list)


class RuleTestResult(BaseModel):
    """Validation report for an individual detection rule against test telemetry."""
    rule_id: str
    rule_title: str
    passed: bool
    true_positives_matched: int
    false_positives_triggered: int
    details: str
